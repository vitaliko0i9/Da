async function seedData() {
  try {
    const habitatCount = await Habitat.countDocuments();
    if (habitatCount === 0) {
      await Habitat.insertMany(habitats);
      console.log(`[Seed] Додано біотопів: ${habitats.length}`);
    }

    const fishCount = await Fish.countDocuments();
    if (fishCount === 0) {
      await Fish.insertMany(fishes);
      console.log(`[Seed] Додано видів риб: ${fishes.length}`);
    }

    const galleryCount = await Gallery.countDocuments();
    if (galleryCount === 0) {
      await Gallery.insertMany(gallery);
      console.log(`[Seed] Додано елементів галереї: ${gallery.length}`);
    }
  } catch (err) {
    console.error("[Seed Error]", err);
  }
}

module.exports = seedData;
